export const availableServices = catalog.filter(
  (service) => MEDIA_ENABLED || !service.media,
);
export const searchKey = (value) =>
  String(value)
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
export function findServices(query = "", category = "") {
  const words = searchKey(query).trim().split(/\s+/).filter(Boolean);
  return availableServices.filter(
    (s) =>
      (!category || s.category === category) &&
      words.every((word) =>
        searchKey(`${s.title} ${s.prompt} ${s.category}`).includes(word),
      ),
  );
}
